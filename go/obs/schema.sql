-- ClickHouse span table (docs/designs/fleet-telemetry.md §1, §4). Applied by the coordinator at start; every statement is idempotent.
CREATE TABLE IF NOT EXISTS span (
  trace_id FixedString(32),
  span_id FixedString(16),
  parent_span_id String,
  service LowCardinality(String),
  host_id LowCardinality(String),
  version LowCardinality(String),
  name LowCardinality(String),
  kind Enum8('server' = 1, 'client' = 2, 'internal' = 3, 'pass' = 4, 'check' = 5),
  start DateTime64(6, 'UTC'),
  duration_ns UInt64,
  outcome Enum8('ok' = 1, 'error' = 2, 'refused' = 3, 'cancelled' = 4),
  error_class LowCardinality(String),
  actor String,
  project_id Nullable(String),
  task_id Nullable(String),
  execution_id Nullable(String),
  experiment_id Nullable(String),
  account_id Nullable(String),
  tokens_in Nullable(UInt64),
  tokens_out Nullable(UInt64),
  tokens_cache_read Nullable(UInt64),
  tokens_cache_write Nullable(UInt64),
  units Nullable(Float64),
  unit_kind LowCardinality(String),
  bytes Nullable(UInt64),
  items Nullable(UInt64),
  retries Nullable(UInt64),
  pg_calls Nullable(UInt32),
  pg_ms Nullable(Float32),
  load1 Nullable(Float64),
  mem_free Nullable(Float64),
  disk_free Nullable(Float64),
  store_free Nullable(Float64),
  cpu_seconds Nullable(Float64),
  rss_bytes Nullable(UInt64),
  peak_rss_bytes Nullable(UInt64),
  open_files Nullable(UInt32),
  attrs Map(LowCardinality(String), String),
  INDEX trace_idx trace_id TYPE bloom_filter GRANULARITY 4,
  INDEX execution_idx execution_id TYPE bloom_filter GRANULARITY 4,
  INDEX project_idx project_id TYPE bloom_filter GRANULARITY 4
) ENGINE = MergeTree
PARTITION BY toYYYYMM(start)
ORDER BY (service, name, start)
SETTINGS non_replicated_deduplication_window = 1000
