package main

import (
	"os"
	"strings"
	"testing"

	"github.com/jackc/pgx/v5"
)

// sqlc cannot parse schema.sql (its migrations hold DO blocks, functions and CTE views), so it reads db/schema.sql:
// every enum, table and view of the migrated database as plain CREATE TYPE / CREATE TABLE (a view as the table of its
// columns) and every plain function by its signature. Requirement S2 (docs/designs/fleet-standard.md). Risk: a migration changes a column and the generated
// queries keep the old type, so a query compiles but fails or misreads at run time.
// FLEET_UPDATE_SQLC_SCHEMA=1 rewrites the file; then run pnpm run go:sqlc.
const sqlcSchemaPath = "db/schema.sql"

func sqlcSchema(t *testing.T, e *testCoordEnv) string {
	t.Helper()
	var b strings.Builder
	b.WriteString("-- Generated by TestMigrationSqlcSchema (sqlc_schema_test.go) from the migrated schema.sql and migrations/; do not edit.\n")
	err := e.ownerStore.Read(e.ctx, nil, func(q *Request) error {
		tx := q.tx
		enums, err := tx.Query(e.ctx, `SELECT t.typname, string_agg(quote_literal(en.enumlabel), ', ' ORDER BY en.enumsortorder)
		 FROM pg_type t JOIN pg_enum en ON en.enumtypid=t.oid JOIN pg_namespace n ON n.oid=t.typnamespace
		 WHERE n.nspname='public' GROUP BY t.typname ORDER BY t.typname`)
		if err != nil {
			return err
		}
		for enums.Next() {
			var name, labels string
			if err := enums.Scan(&name, &labels); err != nil {
				return err
			}
			b.WriteString("CREATE TYPE " + name + " AS ENUM (" + labels + ");\n")
		}
		if err := enums.Err(); err != nil {
			return err
		}
		cols, err := tx.Query(e.ctx, `SELECT c.relname, c.relkind::text, a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull
		 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace JOIN pg_attribute a ON a.attrelid=c.oid
		 WHERE n.nspname='public' AND c.relkind IN ('r','p','v','m') AND a.attnum>0 AND NOT a.attisdropped
		 ORDER BY c.relname, a.attnum`)
		if err != nil {
			return err
		}
		rel := ""
		for cols.Next() {
			var name, kind, col, typ string
			var notNull bool
			if err := cols.Scan(&name, &kind, &col, &typ, &notNull); err != nil {
				return err
			}
			if name != rel {
				if rel != "" {
					b.WriteString("\n);\n")
				}
				if kind == "v" || kind == "m" {
					b.WriteString("-- view\n")
				}
				b.WriteString("CREATE TABLE " + name + " (\n")
				rel = name
			} else {
				b.WriteString(",\n")
			}
			if notNull {
				typ += " NOT NULL"
			}
			b.WriteString("  " + pgx.Identifier{col}.Sanitize() + " " + typ)
		}
		if rel != "" {
			b.WriteString("\n);\n")
		}
		if err := cols.Err(); err != nil {
			return err
		}
		// Plain functions (no trigger, aggregate or procedure; a set-returning one as RETURNS TABLE) by signature, so
		// queries may call them; sqlc reads only the signature, the body is a stub.
		fns, err := tx.Query(e.ctx, `SELECT p.proname, pg_get_function_arguments(p.oid), pg_get_function_result(p.oid)
		 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
		 WHERE n.nspname='public' AND p.prokind='f' AND p.prorettype<>'trigger'::regtype
		 ORDER BY p.proname, pg_get_function_arguments(p.oid)`)
		if err != nil {
			return err
		}
		for fns.Next() {
			var name, args, result string
			if err := fns.Scan(&name, &args, &result); err != nil {
				return err
			}
			b.WriteString("CREATE FUNCTION " + name + "(" + args + ") RETURNS " + result + " LANGUAGE sql AS $$ SELECT NULL $$;\n")
		}
		return fns.Err()
	})
	if err != nil {
		t.Fatal(err)
	}
	return b.String()
}

func TestMigrationSqlcSchema(t *testing.T) {
	e := openTestCoordinator(t, false)
	got := sqlcSchema(t, e)
	if os.Getenv("FLEET_UPDATE_SQLC_SCHEMA") == "1" {
		if err := os.WriteFile(sqlcSchemaPath, []byte(got), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(sqlcSchemaPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(want) != got {
		t.Fatalf("%s differs from the migrated schema: FLEET_UPDATE_SQLC_SCHEMA=1 go test ./coordinator -run TestMigrationSqlcSchema, then pnpm run go:sqlc", sqlcSchemaPath)
	}
}
