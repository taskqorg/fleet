// Builds docs/design-system/book/index.html: one self-contained file (no external requests, under 512 KB).
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { tokensCss } from './tokens.mjs';

const root = new URL('..', import.meta.url);
const common = { bundle: true, minify: true, write: false, format: 'iife', target: 'es2022', jsx: 'automatic', jsxImportSource: 'preact', loader: { '.json': 'json' }, legalComments: 'none' };

async function page(entry, outPath, title, extraCss = '') {
  const res = await build({ ...common, entryPoints: [new URL(entry, root).pathname] });
  const js = res.outputFiles[0].text;
  const css = tokensCss() + readFileSync(new URL('src/styles.css', root), 'utf8') + extraCss;
  const html = `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${title}</title>
<!-- Generated by packages/ui/scripts/build-book.mjs from packages/ui. Do not edit. Icons: Lucide static 1.17.0 (ISC). Synthetic data. -->
<style>${css}</style></head>
<body><div id="app"></div><script>${js.replace(/<\/script/g, '<\\/script')}</script></body></html>
`;
  const out = new URL(outPath, root);
  mkdirSync(new URL('.', out), { recursive: true });
  writeFileSync(out, html);
  console.log(`${outPath.replace('../../', '')}: ${(html.length / 1024).toFixed(0)} KB (limit 512 KB)${html.length > 512 * 1024 ? '  OVER LIMIT' : ''}`);
}
await page('book/book.tsx', '../../docs/design-system/book/index.html', 'Fleet design book', readFileSync(new URL('book/book.css', root), 'utf8'));
await page('book/pages.tsx', '../../docs/design-system/pages/mockups.html', 'Fleet page mockups', 'html,body,#app{height:100%}');
