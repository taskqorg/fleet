// Builds docs/design-system/book/index.html and the pages below: self-contained files (no external requests, under
// 512 KB). They are not committed: .gitignore, GENERATED in scripts/docs-report.ts and the CI design-report artifact list them.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { uiCss } from './tokens.mjs';
import { solidEsbuildPlugin } from './solid-esbuild.mjs';

const root = new URL('..', import.meta.url);
const common = { bundle: true, minify: true, write: false, format: 'iife', target: 'es2022', conditions: ['solid'], plugins: [solidEsbuildPlugin()], loader: { '.json': 'json' }, legalComments: 'none' };

async function page(entry, outPath, title, extraCss = '') {
  const res = await build({ ...common, entryPoints: [new URL(entry, root).pathname] });
  const js = res.outputFiles[0].text;
  const css = uiCss(extraCss);
  const html = `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="color-scheme" content="light dark">
<title>${title}</title>
<!-- Generated by packages/ui/scripts/build-book.mjs from packages/ui. Do not edit. Icons: Lucide static 1.17.0 (ISC). Synthetic data. -->
<style>${css}</style></head>
<body><div id="app"></div><script>${js.replace(/<\/script/g, '<\\/script')}</script></body></html>
`;
  const out = new URL(outPath, root);
  mkdirSync(new URL('.', out), { recursive: true });
  writeFileSync(out, html);
  console.log(`${outPath.replace('../../', '')}: ${(html.length / 1024).toFixed(0)} KB (limit 512 KB)${html.length > 512 * 1024 ? '  OVER LIMIT' : ''}`);
}
await page('book/book.tsx', '../../docs/design-system/book/index.html', 'Fleet design book', readFileSync(new URL('book/book.css', root), 'utf8'));
await page('book/masters.tsx', '../../docs/design-system/book/masters.html', 'Fleet board masters', readFileSync(new URL('book/book.css', root), 'utf8') + '.bm-v{display:grid;grid-template-columns:1fr 1fr;gap:16px;margin-bottom:8px}');
await page('book/pages.tsx', '../../docs/design-system/pages/mockups.html', 'Fleet page mockups', 'html,body,#app{height:100%}');
await page('book/open-questions.tsx', '../../docs/design-system/explorations/open-questions-01.html', 'Fleet open questions 01', readFileSync(new URL('book/oq.css', root), 'utf8'));
