// Builds docs/design-system/book/index.html: one self-contained file (no external requests, under 512 KB).
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { tokensCss } from './tokens.mjs';

const root = new URL('..', import.meta.url);
const out = new URL('../../../docs/design-system/book/index.html', import.meta.url);
const common = { bundle: true, minify: true, write: false, format: 'iife', target: 'es2022', jsx: 'automatic', jsxImportSource: 'preact', loader: { '.json': 'json' }, legalComments: 'none' };

const book = await build({ ...common, entryPoints: [new URL('book/book.tsx', root).pathname] });
const js = book.outputFiles[0].text;
const css = tokensCss() + readFileSync(new URL('src/styles.css', root), 'utf8') + readFileSync(new URL('book/book.css', root), 'utf8');
const html = `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Fleet design book</title>
<!-- Generated by packages/ui/scripts/build-book.mjs from packages/ui. Do not edit. Icons: Lucide static 1.17.0 (ISC). -->
<style>${css}</style></head>
<body><div id="app"></div><script>${js.replace(/<\/script/g, '<\\/script')}</script></body></html>
`;
mkdirSync(new URL('.', out), { recursive: true });
writeFileSync(out, html);
console.log(`book: ${out.pathname} ${(html.length / 1024).toFixed(0)} KB (limit 512 KB)`);
if (html.length > 512 * 1024) console.warn('warning: book is over 512 KB');
