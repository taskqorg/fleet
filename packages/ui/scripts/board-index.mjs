// Lists every top-level frame of the design board in docs/design-system/board/index.json, so an agent finds the
// frame a task names (by id, page, width or status) without opening the canvases. Run: pnpm run board:index.
// Drafts (board/drafts/, git-ignored) are not listed: only committed canvases are a reference.
import { existsSync, readFileSync, readdirSync, writeFileSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const BOARD = fileURLToPath(new URL('../../../docs/design-system/board/', import.meta.url));
export const INDEX = join(BOARD, 'index.json');

function canvases(dir) {
  return readdirSync(dir).flatMap(f => {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) return ['drafts', 'Assets', 'Styles', 'Exports'].includes(f) || f.startsWith('.') ? [] : canvases(p);
    return f.endsWith('.bl') ? [p] : [];
  });
}

// A top-level row: 16 hex id at column 0, its geometry, its name as the row's last quoted string.
const TOP = /^([0-9a-f]{16}) (.*)"((?:[^"\\]|\\.)*)"\s*$/;

/** The frame's status as its name states it: approved, superseded, draft or built; null when the name says none. */
export function statusOf(name) {
  const n = name.toLowerCase();
  if (n.includes('superseded')) return 'superseded';
  if (n.includes('approved') || /\bowner pick\b/.test(n)) return 'approved';
  if (n.includes('draft')) return 'draft';
  if (n.includes('built')) return 'built';
  return null;
}

export function framesOf(text, canvas) {
  const out = [];
  for (const line of text.split('\n')) {
    const m = TOP.exec(line);
    if (!m) continue;
    const [, id, rest, raw] = m;
    const name = raw.replace(/\\"/g, '"');
    const size = /\bs\((?:hug:)?(\d+(?:\.\d+)?)/.exec(rest);
    const width = /\b(1440|390|1100|768)\b/.exec(name)?.[1];
    out.push({
      id, canvas, name,
      page: canvas.startsWith('screens/') ? canvas.slice('screens/'.length) : null,
      width: width ? Number(width) : null,
      frameWidth: size ? Math.round(Number(size[1])) : null,
      theme: rest.includes('theme(light)') ? 'light' : rest.includes('theme(dark)') ? 'dark' : null,
      component: /\bcomp\b/.test(rest),
      status: statusOf(name),
    });
  }
  return out;
}

export function boardIndex() {
  const frames = canvases(BOARD).sort().flatMap(p => framesOf(readFileSync(p, 'utf8'), relative(BOARD, p).replace(/\.bl$/, '')));
  return { comment: 'GENERATED by packages/ui/scripts/board-index.mjs (pnpm run board:index); do not edit.', frames };
}

// The code map: each master on board/components.bl with the packages/ui exports its book section renders, the
// control spec and the book anchor, so an agent building from a frame imports the real control (Code Connect's idea).
export const CODE_MAP = join(BOARD, 'code-map.json');
const UI = fileURLToPath(new URL('../', import.meta.url));

function exportsOf() {
  const out = new Map();
  const walk = d => readdirSync(d).forEach(f => {
    const p = join(d, f);
    if (statSync(p).isDirectory()) return walk(p);
    if (!p.endsWith('.tsx')) return;
    for (const m of readFileSync(p, 'utf8').matchAll(/^export (?:function|const) ([A-Z][A-Za-z0-9]*)/gm))
      if (!out.has(m[1])) out.set(m[1], relative(join(UI, '..', '..'), p));
  });
  walk(join(UI, 'src'));
  return out;
}

export function codeMap() {
  const ex = exportsOf();
  const book = readdirSync(join(UI, 'book')).filter(f => f.endsWith('.tsx')).map(f => readFileSync(join(UI, 'book', f), 'utf8')).join('\n');
  // Each function or const component of the book, with its body up to the next top-level declaration.
  const funcs = new Map();
  const decl = [...book.matchAll(/(?:^|\n)(?:export )?(?:function|const) ([A-Z][A-Za-z0-9]*)\b/g)];
  decl.forEach((m, i) => funcs.set(m[1], book.slice(m.index + m[0].length, decl[i + 1]?.index ?? m.index + 4000)));
  const used = (body, seen) => {
    const out = new Set();
    for (const [, t] of body.matchAll(/<([A-Z][A-Za-z0-9]*)/g)) {
      if (ex.has(t)) out.add(t);
      else if (funcs.has(t) && !seen.has(t)) { seen.add(t); used(funcs.get(t), seen).forEach(x => out.add(x)); }
    }
    return out;
  };
  const masters = new Map();
  const comp = readFileSync(join(BOARD, 'components.bl'), 'utf8');
  for (const m of comp.matchAll(/^ {2}([0-9a-f]{16}) [^\n]*\bcomp\b[^\n]*"([^"]+)"\s*$/gm)) masters.set(m[2], m[1]);
  const rows = [];
  // A book section: ['<id>', '<title>', '<spec>', () => <Demo />, ...].
  for (const [, id, title, spec, render] of book.matchAll(/\['([a-z0-9-]+)', '([^']+)', '([a-z0-9-]*)', \(\) => (.{0,300}?)(?:, \(\) =>|\])/g)) {
    const specPath = `docs/design-system/controls/${spec}.md`;
    rows.push({
      master: title, id: masters.get(title) ?? null, canvas: 'components',
      book: `docs/design-system/book/index.html#${id}`,
      spec: spec && existsSync(join(UI, '..', '..', specPath)) ? specPath : null,
      imports: [...used(render, new Set())].sort().map(name => ({ name, from: 'packages/ui/src/index.ts', file: ex.get(name) })),
    });
  }
  return { comment: 'GENERATED by packages/ui/scripts/board-index.mjs (pnpm run board:index); do not edit.', masters: rows };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const idx = boardIndex();
  writeFileSync(INDEX, JSON.stringify(idx, null, 1) + '\n');
  console.log(`${relative(process.cwd(), INDEX)}: ${idx.frames.length} frames`);
  if (existsSync(join(BOARD, 'components.bl'))) {
    const cm = codeMap();
    writeFileSync(CODE_MAP, JSON.stringify(cm, null, 1) + '\n');
    console.log(`${relative(process.cwd(), CODE_MAP)}: ${cm.masters.length} masters, ${cm.masters.filter(m => m.id).length} on the board`);
  }
}
